#!/usr/bin/env python3
#
# ******************************************************************************
#
# BBC MASTER ELITE LAYOUT INFORMATION SCRIPT
#
# Run by the Makefile from the repository's root, after the game has been
# assembled. From the game's symbols (3-assembled-output/symbols.txt, which
# "beebasm -d" writes) and the per-area copies of the source that
# 2-build-files/streams.py writes, it produces:
#
#   * 3-assembled-output/banks.txt: each label of code in sideways RAM, with
#     the ROMSEL value of its bank in hex (4: Elite's home bank, 7: the cold
#     area), for the harness (6-harness/mlib.mjs) and bankcheck.py
#
#   * 3-assembled-output/game-addresses.asm: the addresses and lengths that
#     the loader (elite-loader.asm) needs from the game: the entry point S%
#     and its bank, where BCODE loads, the HAZEL image, DFSST and the cold
#     area's length
#
#   * 3-assembled-output/images.txt: where the loader puts each image, for
#     the harness (6-harness/mboot.mjs): file, ROMSEL (hex) or main, shadow
#     or hazel, start (hex), and "v" for images holding variables or code
#     that modifies itself
#
# ******************************************************************************

import os
import re

OUT = "3-assembled-output/"
SRC = "1-source-files/main-sources/"

sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open(OUT + "symbols.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))


def labels(path):
    return re.findall(r"^\.([A-Za-z_][\w%]*)", open(path, encoding="latin-1").read(), re.M)


# The banks of the labels in sideways RAM: the blocks tagged bank 4 and cold,
# and the main code's run where it continues into bank 4 (its labels at
# &8000-&BFFF)

BANKED = [(OUT + "elite-source-bank4.asm", "4"), (OUT + "elite-source-cold.asm", "7")]

with open(OUT + "banks.txt", "w") as f:
    for path, bank in BANKED:
        if os.path.exists(path):
            for name in labels(path):
                f.write("%s %s\n" % (name, bank))
    for name in labels(OUT + "elite-source-run.asm"):
        if 0x8000 <= sy.get(name, 0) < 0xC000:
            f.write("%s 4\n" % name)

banks = {}
for line in open(OUT + "banks.txt"):
    name, bank = line.split()
    banks[name] = int(bank, 16)

# The loader's addresses

bcode = re.search(r"^S\.BCODE &([0-9A-F]+)", open(OUT + "compile.txt").read(), re.M).group(1)

with open(OUT + "game-addresses.asm", "w") as f:
    f.write("\\ Generated by 2-build-files/layout-info.py\n")
    f.write(" S%% = &%04X\n" % sy["S%"])
    f.write(" SBANK = &%02X\n" % banks.get("S%", 4))
    f.write(" HZ_START = &%04X\n" % sy["HZ_START"])
    f.write(" HZLEN = &%04X\n" % (sy["HZ_END"] - sy["HZ_START"]))
    f.write(" BCODEAT = &%s\n" % bcode)
    f.write(" DFSST = &%04X\n" % sy["DFSST"])
    f.write(" C7LEN = &%04X\n" % (sy["COLD_END%"] - 0x8000))
    f.write(" HILEN = &1000\n")

# The images the loader installs

with open(OUT + "images.txt", "w") as f:
    for img, rs, at, v in (("BANK4.bin", "4", 0x8000, "v"), ("COLD7.bin", "7", 0x8000, ""),
                           ("HAZEL.bin", "hazel", sy["HZ_START"], "v"),
                           ("HICODE.bin", "main", 0x7000, "v")):
        f.write("%s %s %04X %s\n" % (img, rs, at, v))
