#!/usr/bin/env python3
#
# ******************************************************************************
#
# BBC MASTER ELITE LAYOUT INFORMATION SCRIPT
#
# Run by the Makefile from the repository's root, after the game has been
# assembled. From the game's symbols (3-assembled-output/symbols.txt, which
# "beebasm -d" writes) and the copies of the source that
# 2-build-files/streams.py writes for each pass, it produces:
#
#   * 3-assembled-output/banks.txt: each label of code in sideways RAM, with
#     the ROMSEL value of its bank in hex (4: Elite's home bank, 7: the cold
#     area; with the filled renderer, 5: the rasteriser, 85: its polygon
#     window in ANDY, 6: the frame layer, 7 again: the meridian window after
#     the cold area, with the lens flare), for the harness
#     (6-harness/mlib.mjs) and bankcheck.py
#
#   * 3-assembled-output/game-addresses.asm: the addresses and lengths that
#     the loader (elite-loader.asm) needs from the game: the entry point S%
#     and its bank, where BCODE loads, the HAZEL image, DOSCLI's stash (DFSST, DFSST2, DFSIN) and the cold
#     area's length (and with the renderer, the lengths of its images,
#     G_INIT, and where the meridian window goes)
#
#   * 3-assembled-output/images.txt: where the loader puts each image, for
#     the harness (6-harness/mboot.mjs): file, ROMSEL (hex) or main, shadow
#     or hazel, start (hex), and "v" for images holding variables or code
#     that modifies itself
#
# ******************************************************************************

import os
import re

OUT = "3-assembled-output/"
SRC = "1-source-files/main-sources/"

sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open(OUT + "symbols.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))


def labels(path):
    return re.findall(r"^\.([A-Za-z_][\w%]*)", open(path, encoding="latin-1").read(), re.M)


# The banks of the labels in sideways RAM: the hot pass's container in bank 4
# and the hot data after it, and the cold pass

BANKED = [(OUT + "elite-source-hot3.asm", "4"), (OUT + "elite-data-hot4.asm", "4"),
          (OUT + "dashtab-scan.asm", "4"), (OUT + "dashtab-dot.asm", "4"), (OUT + "dashtab-spbt.asm", "4"),
          (OUT + "dashtab-ecbt.asm", "4"), (OUT + "dashtab-msbar.asm", "4"),
          (OUT + "elite-source-cold.asm", "7"),
          (SRC + "gfx-raster.asm", "5"), (SRC + "gfx-raster_disc.asm", "5"), (SRC + "gfx-raster_poly.asm", "85"),
          (SRC + "gfx-raster_line.asm", "85"), (SRC + "gfx-raster_lcold.asm", "5"),
          (SRC + "gfx-raster_kept.asm", "5"),
          (SRC + "gfx-frame.asm", "6"), (SRC + "gfx-flare6.asm", "6"),
          (SRC + "gfx-hangar.asm", "6"), (SRC + "gfx-faces.asm", "6"), (SRC + "gfx-frame_cold.asm", "6"),
          (SRC + "gfx-merid.asm", "7"), (SRC + "gfx-kept7.asm", "7"),
          (SRC + "gfx-flare.asm", "7")]

# Each name is written once, from the first file that defines it: the game's
# copies come first, and a name they share with a scoped local label of the
# renderer's (.t2, .out ...) is the game's

seen = set()
with open(OUT + "banks.txt", "w") as f:
    for path, bank in BANKED:
        if os.path.exists(path):
            for name in labels(path):
                if name not in seen:
                    seen.add(name)
                    f.write("%s %s\n" % (name, bank))

banks = {}
for line in open(OUT + "banks.txt"):
    name, bank = line.split()
    banks[name] = int(bank, 16)

# The loader's addresses

bcode = re.search(r"^S\.BCODE &([0-9A-F]+)", open(OUT + "compile.txt").read(), re.M).group(1)

with open(OUT + "game-addresses.asm", "w") as f:
    f.write("\\ Generated by 2-build-files/layout-info.py\n")
    f.write(" S%% = &%04X\n" % sy["S%"])
    f.write(" SBANK = &%02X\n" % banks.get("S%", 4))
    f.write(" HZ_START = &%04X\n" % sy["HZ_START"])
    f.write(" HZLEN = &%04X\n" % (sy["HZ_END"] - sy["HZ_START"]))
    f.write(" BCODEAT = &%s\n" % bcode)
    f.write(" DFSST = &%04X\n" % sy["DFSST"])
    if "DFSST2" in sy:                  # DOSCLI's stash, in two halves
        f.write(" DFSST2 = &%04X\n" % sy["DFSST2"])
        f.write(" DFSIN = &%04X\n" % sy["DFSIN"])
    f.write(" C7LEN = &%04X\n" % (sy["COLD_END%"] - 0x8000))
    f.write(" HILEN = &1000\n")
    if "B5_END" in sy:
        f.write(" B5LEN = &%04X\n" % (sy["B5_END"] - 0x8000))
        f.write(" RALEN = &%04X\n" % (sy["RA_END"] - 0x8000))
    if "B6_END" in sy:
        f.write(" B6LEN = &%04X\n" % (sy["B6_END"] - 0x8000))
        f.write(" GINIT = &%04X\n" % sy["G_INIT"])
    if "MERID_START" in sy:
        f.write(" M7AT = &%04X\n" % sy["MERID_START"])
        f.write(" M7LEN = &%04X\n" % (sy["MERID_END"] - sy["MERID_START"]))

# The images the loader installs

with open(OUT + "images.txt", "w") as f:
    images = [("BANK4.bin", "4", 0x8000, "v"), ("COLD7.bin", "7", 0x8000, "")]
    if "MERID_START" in sy:
        images += [("MERID.bin", "7", sy["MERID_START"], "v")]
    if "B5_END" in sy:
        images += [("BANK5.bin", "5", 0x8000, "v"), ("RASTA.bin", "85", 0x8000, "v")]
    if "B6_END" in sy:
        images += [("BANK6.bin", "6", 0x8000, "v")]
    images += [("HAZEL.bin", "hazel", sy["HZ_START"], "v"), ("HICODE.bin", "main", 0x7000, "v")]
    for img, rs, at, v in images:
        f.write("%s %s %04X %s\n" % (img, rs, at, v))
